// Generate `api/_lib/revert-selectors.ts` from the contracts' own error declarations.
//
// Written after a hand-built table got 12 of 16 selectors wrong. The mistake was subtle and silent:
// the extraction stripped whitespace inside the parameter list, so `SettledBelowFloor(address
// recipient, ...)` was hashed as `SettledBelowFloor(addressrecipient, ...)`. `cast sig` hashes
// whatever string it is handed, so every selector came back well-formed and wrong, and the only
// ones that survived were the errors with no parameters at all.
//
// Hashed with viem rather than shelling out to `cast`, so the generator needs no Foundry on PATH.
// The output was cross-checked once against `cast sig`, which shares none of this code.
//
// A wrong selector here does not throw. It decodes a real floor refusal as `unknown`, and the
// refusal counter — the number the whole product is about — reads zero while the guard is working.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { keccak256, toHex } from "viem";

const roots = ["../contracts/src/subfloor", "../contracts/src/routers"];

function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (p.endsWith(".sol")) out.push(p);
  }
  return out;
}

const errors = new Map();
for (const root of roots) {
  for (const file of walk(root)) {
    const src = readFileSync(file, "utf8");
    for (const m of src.matchAll(/\berror\s+([A-Za-z0-9_]+)\s*\(([^)]*)\)\s*;/g)) {
      const name = m[1];
      const params = m[2].trim();
      // The canonical signature is types only. Parameter names and location keywords are dropped,
      // which is exactly the step the hand-built table got wrong.
      const types = params ? params.split(",").map((p) => p.trim().split(/\s+/)[0]) : [];
      errors.set(`${name}(${types.join(",")})`, name);
    }
  }
}

const rows = [...errors]
  .sort((a, b) => a[1].localeCompare(b[1]))
  .map(([sig, name]) => {
    const sel = keccak256(toHex(sig)).slice(0, 10);
    return `  "${sel}": "${name}", // ${sig}`;
  });

writeFileSync(
  "api/_lib/revert-selectors.ts",
  `// GENERATED by scripts/gen-revert-selectors.mjs from the contracts. Do not edit by hand.
//
// Every custom error the router or the registry can revert with, keyed by its four-byte selector.
// Regenerate with \`npm run gen:selectors\`; \`npm run check\` fails if this file is stale.

export const REVERT_REASONS: Record<string, string> = {
${rows.join("\n")}
};
`,
);

console.log(`wrote ${rows.length} selectors`);
